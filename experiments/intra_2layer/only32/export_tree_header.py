#!/usr/bin/env python3
"""Export the trained ONLY32 tree as integer-only x265/C-style comparisons."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent


def condition(feature: str, threshold: float, c_mode: bool = False) -> str:
    # Ratios use threshold scaled by 1e6.  Cross-products are uint64_t.
    t = int(round(threshold * 1_000_000))
    simple = {
        "edge4": "f.edge4", "edge8": "f.edge8", "edge16": "f.edge16",
        "edge32": "f.edge32", "qp": "qp",
    }
    if c_mode:
        simple = {key: value.replace("f.", "f->") for key, value in simple.items()}
    if feature in simple:
        return f"{simple[feature]} <= {threshold:.12g}"
    numerator, denominator, scale = {
        "sad32/qstep": ("f.sad32", "f.qstepQ8", 256),
        "sad16/qstep": ("f.sad16", "f.qstepQ8", 256),
        "sad8/qstep": ("f.sad8", "f.qstepQ8", 256),
        "gain32/qstep": ("gain32", "f.qstepQ8", 256),
        "gain8/qstep": ("gain8", "f.qstepQ8", 256),
        "grad/qstep": ("grad", "f.qstepQ8", 256),
        "lap/qstep": ("f.laplacian", "f.qstepQ8", 256),
        "anisotropy/qstep": ("anisotropy", "f.qstepQ8", 256),
        "gain8/sad16": ("gain8", "f.sad16 + 1", 1),
        "gain32/sad32": ("gain32", "f.sad32 + 1", 1),
        "grad/sad8": ("grad", "f.sad8 + 1", 1),
        "lap/grad": ("f.laplacian", "grad + 1", 1),
        "sad32/qstep2": ("f.sad32", "(uint64_t)f.qstepQ8 * f.qstepQ8", 65536),
        "sad16/qstep2": ("f.sad16", "(uint64_t)f.qstepQ8 * f.qstepQ8", 65536),
        "sad8/qstep2": ("f.sad8", "(uint64_t)f.qstepQ8 * f.qstepQ8", 65536),
        "grad/qstep2": ("grad", "(uint64_t)f.qstepQ8 * f.qstepQ8", 65536),
        "lap/qstep2": ("f.laplacian", "(uint64_t)f.qstepQ8 * f.qstepQ8", 65536),
    }[feature]
    if c_mode:
        numerator = numerator.replace("f.", "f->")
        denominator = denominator.replace("f.", "f->")
        numerator = numerator.replace("qstepQ8", "qstep_q8")
        denominator = denominator.replace("qstepQ8", "qstep_q8")
    return f"(uint64_t)({numerator}) * {scale}000000ULL <= {t}ULL * ({denominator})"


def emit_node(node: dict, depth: int = 1, c_mode: bool = False) -> list[str]:
    indent = "    " * depth
    if node["feature"] < 0:
        score = int(round(node["probability"] * 100))
        return [f"{indent}return {score}; /* n={node['samples']}, p32={node['probability']:.4f} */"]
    result = [f"{indent}if ({condition(node['feature_name'], node['threshold'], c_mode)})"]
    result += emit_node(node["left"], depth + 1, c_mode)
    result.append(f"{indent}else")
    result += emit_node(node["right"], depth + 1, c_mode)
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", type=Path, default=HERE / "model" / "only32_tree.json")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--c", action="store_true", help="emit C for IntraLayerFeaturesC")
    args = parser.parse_args()
    model = json.loads(args.model.read_text(encoding="utf-8"))
    body = "\n".join(emit_node(model["tree"], c_mode=args.c))
    if args.c:
        signature = "static uint32_t intra_only32_score(const IntraLayerFeaturesC *f)"
        prelude = '''    const uint32_t gain32 = f->sad32 > f->sad16 ? f->sad32 - f->sad16 : 0;
    const uint32_t grad = f->grad_h + f->grad_v;
    const uint32_t anisotropy = f->grad_h > f->grad_v ? f->grad_h - f->grad_v : f->grad_v - f->grad_h;'''
    else:
        signature = "static inline uint32_t intraOnly32Probability(const IntraLayerFeatures& f, int qp)"
        prelude = '''    const uint32_t gain32 = f.sad32 > f.sad16 ? f.sad32 - f.sad16 : 0;
    const uint32_t grad = f.gradH + f.gradV;
    const uint32_t anisotropy = f.gradH > f.gradV ? f.gradH - f.gradV : f.gradV - f.gradH;
    (void)qp;'''
    text = f'''/* Generated by only32_study/export_tree_header.py. */
#ifndef X265_INTRA_ONLY32_GATE_H
#define X265_INTRA_ONLY32_GATE_H

{signature}
{{
{prelude}
{body}
}}

#endif
'''
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(args.out)


if __name__ == "__main__":
    main()
